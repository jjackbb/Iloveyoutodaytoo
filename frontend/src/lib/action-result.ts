/**
 * 서버 액션이 성공/실패를 돌려주는 공통 모양.
 *
 * 왜 별도 파일인가: 'use server' 파일은 async 함수 외에 값을 export 할 수 없다.
 * 타입은 컴파일 때 지워지므로 거기 둬도 되지만, 여러 액션 파일이 같은 모양을
 * 각자 적어두면 조용히 어긋난다. 한 곳에 둔다.
 *
 * 왜 필요한가: 액션이 `Promise<void>` 면 화면은 실패를 알 방법이 없다.
 * 실제로 ♡·즐겨찾기·알림 삭제·사서함 치우기가 전부 실패해도 console.error 만 남기고
 * 성공처럼 끝났다 — 사용자에게는 "눌렀는데 아무 일도 안 일어남"으로 보였고,
 * 사서함 치우기는 한술 더 떠 편집 모드를 닫고 고른 것을 비워 **치워진 것처럼** 굴었다.
 *
 * error 는 사용자에게 그대로 보여줄 문구다. 원인은 서버 로그에 남기고,
 * 화면에는 다음에 무엇을 하면 되는지만 적는다.
 *
 * 필드 이름을 error 로 맞춘 이유: 이미 PushActionResult · CommentActionResult ·
 * MemoryActionResult 셋이 같은 모양을 쓰고 있다. 여기서만 message 로 두면
 * 같은 뜻의 값이 파일마다 다른 이름을 갖게 된다.
 * (저 셋을 이 타입의 별칭으로 합치는 일은 이번 작업 범위가 아니라 남겨둔다.)
 */
export type ActionResult = { ok: true } | { ok: false; error: string }

/** 연결이 흔들렸을 때 공통으로 쓰는 문구. 같은 상황에 같은 말을 하기 위해. */
export const RETRY_MESSAGE = '잘 안 됐어요. 잠시 후 다시 시도해주세요.'
